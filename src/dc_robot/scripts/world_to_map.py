#!/usr/bin/env python3
"""Make a "floor-plan" occupancy map (like a CAD drawing) directly from a Gazebo world.

Real data centres have accurate CAD floor plans, and robot fleets often localise against a
map made from them instead of one they built themselves. This script does the same for our
worlds: every collision box / cylinder that crosses the lidar's scan plane (0.22 m above the
floor) is drawn as occupied, the rest of the building as free. The result is a map_server
map whose frame matches the SLAM maps (map origin = the robot's spawn point).

Usage (from the workspace root):
    python3 src/dc_robot/scripts/world_to_map.py --world datacenter --spawn -4.95 -2.75
Writes maps/<world>.pgm and .yaml (use --out to choose another name).

Only static models are drawn; the clutter models of *_busy worlds are skipped on purpose
(those are the unmapped obstacles), so pass the clean world.
"""
import argparse
import os
import xml.etree.ElementTree as ET

import numpy as np

PKG = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
LIDAR_Z = 0.22      # scan plane height above the floor (sensors.xacro)
RES = 0.05          # m per cell, same as the SLAM maps


def shapes(world_file):
    """Yield (kind, x, y, sx_or_radius, sy, zmin, zmax) for every collision in the world."""
    for link in ET.parse(world_file).getroot().iter('link'):
        geom = link.find('collision/geometry')
        if geom is None:
            continue
        x, y, z = map(float, link.find('pose').text.split()[:3])
        box = geom.find('box/size')
        if box is not None:
            sx, sy, sz = map(float, box.text.split())
            yield 'box', x, y, sx, sy, z - sz / 2, z + sz / 2
        else:
            r = float(geom.find('cylinder/radius').text)
            h = float(geom.find('cylinder/length').text)
            yield 'cyl', x, y, r, r, z - h / 2, z + h / 2


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--world', default='datacenter', help='world name in worlds/')
    ap.add_argument('--spawn', nargs=2, type=float, default=[-4.95, -2.75],
                    help='robot spawn x y in the world (= map origin)')
    ap.add_argument('--out', default=None, help='output base name in maps/ (default: world)')
    ap.add_argument('--margin', type=float, default=1.0, help='free border around the walls (m)')
    args = ap.parse_args()

    world_file = os.path.join(PKG, 'worlds', args.world + '.world')
    seen = [s for s in shapes(world_file) if s[5] <= LIDAR_Z <= s[6]]

    def half(s, i):     # half-extent: boxes store full size, cylinders the radius
        return s[i] / 2 if s[0] == 'box' else s[i]
    xs = [s[1] + k * half(s, 3) for s in seen for k in (-1, 1)]
    ys = [s[2] + k * half(s, 4) for s in seen for k in (-1, 1)]
    x0, x1 = min(xs) - args.margin, max(xs) + args.margin
    y0, y1 = min(ys) - args.margin, max(ys) + args.margin
    w, h = int(np.ceil((x1 - x0) / RES)), int(np.ceil((y1 - y0) / RES))

    # cell centres in world coordinates; row 0 = bottom (south) edge
    cx = x0 + (np.arange(w) + 0.5) * RES
    cy = y0 + (np.arange(h) + 0.5) * RES
    occ = np.zeros((h, w), dtype=bool)
    for kind, x, y, a, b, _, _ in seen:
        if kind == 'box':
            ix = (cx >= x - a / 2) & (cx <= x + a / 2)
            iy = (cy >= y - b / 2) & (cy <= y + b / 2)
            occ |= np.outer(iy, ix)
        else:
            occ |= ((cx[None, :] - x) ** 2 + (cy[:, None] - y) ** 2) <= a * a

    img = np.where(occ, 0, 254).astype(np.uint8)[::-1]      # image row 0 = top (north)
    base = args.out or args.world
    maps = os.path.join(PKG, 'maps')
    with open(os.path.join(maps, base + '.pgm'), 'wb') as f:
        f.write(b'P5\n# floor-plan map generated by world_to_map.py\n')
        f.write(f'{w} {h}\n255\n'.encode())
        f.write(img.tobytes())
    sx, sy = args.spawn
    with open(os.path.join(maps, base + '.yaml'), 'w') as f:
        f.write(f'# Floor-plan map of worlds/{args.world}.world, generated by '
                'scripts/world_to_map.py.\n# Map frame = robot spawn point; obstacles = '
                f'everything crossing the lidar plane ({LIDAR_Z} m).\n')
        f.write(f'image: {base}.pgm\nmode: trinary\nresolution: {RES}\n'
                f'origin: [{x0 - sx:.3f}, {y0 - sy:.3f}, 0]\nnegate: 0\n'
                'occupied_thresh: 0.65\nfree_thresh: 0.25\n')
    print(f'{len(seen)} shapes cross the scan plane -> {maps}/{base}.pgm/.yaml ({w}x{h})')


if __name__ == '__main__':
    main()
