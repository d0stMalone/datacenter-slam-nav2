def datahall():
    """20 x 14 m data-centre hall (x in [-10, 10], y in [-7, 7]).

    Rack rows run along x, in hot/cold-aisle layout:

        y =  6.45  CRAC cooling units along the north wall
        y =  4.0   row A   (fronts face north, cold side)
                   -- hot aisle --
        y =  1.6   row B   (fronts face south)
                   -- cold aisle --
        y = -0.8   row C   (fronts face north)
                   -- hot aisle --
        y = -3.2   row D   (fronts face south)
        y < -3.8   open service area: UPS cabinets, robot start point

    Each row is split by a 1.8 m cross aisle (x in [-1.4, 0.4]), so the planner has loops and
    alternative routes. East side: NOC office (NE), building columns + PDUs, and a fenced
    storage cage (SE). The outer walls have no openings, so the map is a closed region (the
    frontier explorer in Phase 5 relies on that).

    Rack aisles are 1.2 m wide, the real-world standard; with a 0.35 m robot that's a
    meaningful test for Nav2's costmap inflation.
    """
    W_T, W_H = 0.2, 2.5          # wall thickness / height
    shapes = []

    # --- outer shell (inner faces at x = +-9.9, y = +-6.9) ---
    shapes += [
        wall('wall_north', -10, 7, 10, 7, W_T, W_H, 'Gazebo/White'),
        wall('wall_south', -10, -7, 10, -7, W_T, W_H, 'Gazebo/White'),
        wall('wall_west', -10, -7, -10, 7, W_T, W_H, 'Gazebo/White'),
        wall('wall_east', 10, -7, 10, 7, W_T, W_H, 'Gazebo/White'),
    ]

    # --- rack rows: standard 600 mm wide x 1200 mm deep x 2.0 m (42U) cabinets ---
    RACK_W, RACK_D, RACK_H = 0.6, 1.2, 2.0
    rows = {'A': (4.0, +1), 'B': (1.6, -1), 'C': (-0.8, +1), 'D': (-3.2, -1)}  # y, front dir
    blocks = [(-8.6, 12), (0.4, 7)]  # (x start, rack count): west block, east block
    for row, (y, front) in rows.items():
        for b, (x0, count) in enumerate(blocks):
            for i in range(count):
                x = x0 + RACK_W * (i + 0.5)
                name = f'rack_{row}{b + 1}_{i + 1:02d}'
                # visual_scale < 1 leaves a thin seam so individual cabinets are visible,
                # while the collision boxes still touch (the lidar sees one solid row).
                shapes.append(Box(name, x, y, RACK_W, RACK_D, RACK_H,
                                  'Gazebo/Black', visual_scale=0.97))
                # Status-LED strip on the cabinet front (decoration only).
                led_material = 'Gazebo/BlueGlow' if i % 5 == 2 else 'Gazebo/GreenGlow'
                shapes.append(Box(f'{name}_leds', x, y + front * (RACK_D / 2 + 0.005),
                                  0.4, 0.01, 0.03, led_material, z=1.6, collide=False))

    # --- CRAC (computer-room air conditioning) units along the north wall ---
    for i, x in enumerate([-7.0, -3.5, 0.0, 3.5]):
        shapes.append(Box(f'crac_{i + 1}', x, 6.45, 2.0, 0.9, 1.9, 'Gazebo/Grey'))

    # --- UPS battery cabinets along the south wall (service area) ---
    for i, x in enumerate([-8.9, -7.6, -6.3]):
        shapes.append(Box(f'ups_{i + 1}', x, -6.45, 1.2, 0.8, 1.9, 'Gazebo/DarkGrey'))

    # --- NOC office in the NE corner (door in its south wall at x in [7.6, 8.6]) ---
    shapes += [
        wall('noc_wall_west', 6.5, 2.6, 6.5, 6.9, 0.15, W_H, 'Gazebo/White'),
        wall('noc_wall_south_a', 6.5, 2.6, 7.6, 2.6, 0.15, W_H, 'Gazebo/White'),
        wall('noc_wall_south_b', 8.6, 2.6, 9.9, 2.6, 0.15, W_H, 'Gazebo/White'),
        Box('noc_desk', 8.2, 5.9, 2.4, 0.8, 0.75, 'Gazebo/Wood'),
        Box('noc_cabinet', 7.0, 4.0, 0.5, 1.2, 1.2, 'Gazebo/Grey'),
    ]

    # --- building columns and power distribution ---
    shapes += [
        Cylinder('column_1', 6.0, 0.4, 0.25, W_H, 'Gazebo/White'),
        Cylinder('column_2', 6.0, -3.0, 0.25, W_H, 'Gazebo/White'),
        Cylinder('column_3', -0.5, -5.4, 0.25, W_H, 'Gazebo/White'),
        Box('pdu_1', 9.5, 0.6, 0.6, 0.8, 1.8, 'Gazebo/Yellow'),
        Box('pdu_2', 9.5, -0.8, 0.6, 0.8, 1.8, 'Gazebo/Yellow'),
    ]

    # --- fenced storage cage in the SE corner (gate at x in [7.0, 8.0]) ---
    # Real mesh fencing is see-through; here it's solid for the lidar but drawn translucent.
    fence = dict(thickness=0.05, height=2.2, material='Gazebo/Grey')
    for s in [wall('cage_north_a', 6.0, -4.0, 7.0, -4.0, **fence),
              wall('cage_north_b', 8.0, -4.0, 9.9, -4.0, **fence),
              wall('cage_west', 6.0, -6.9, 6.0, -4.0, **fence)]:
        s.transparency = 0.6
        shapes.append(s)
    shapes += [
        Box('cage_crate_1', 9.2, -6.3, 1.0, 1.0, 0.8, 'Gazebo/WoodPallet'),
        Box('cage_crate_2', 6.8, -6.4, 1.0, 0.8, 1.2, 'Gazebo/WoodPallet'),
    ]

    description = """  datahall.world: 20 m x 14 m data-centre hall for SLAM / navigation testing.
  Four rows of 42U racks in a hot/cold-aisle layout (1.2 m aisles), split by a cross aisle;
  CRAC units, UPS cabinets, PDUs, columns, a NOC office and a fenced storage cage.
  Robot spawn point (see sim.launch.py): (-6.0, -5.2)."""
    return build_sdf('datahall', description, shapes, '0 -17 19 0 0.85 1.5708')


