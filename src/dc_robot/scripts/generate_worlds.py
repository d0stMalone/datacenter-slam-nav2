#!/usr/bin/env python3
"""Generate the Gazebo worlds in ../worlds/ from compact layout tables.

Each world is a list of primitive shapes (boxes and cylinders) merged into one static model.
Defining layouts in code keeps them easy to tweak (move a rack row, widen an aisle) and
reproducible.

    python3 scripts/generate_worlds.py            # regenerate all worlds
    python3 scripts/generate_worlds.py datahall   # just one

Design rule for every world: obstacles the robot must avoid are taller than the lidar scan
plane (~0.22 m above the floor), otherwise the 2D lidar cannot see them.
"""
from dataclasses import dataclass
from pathlib import Path
import sys

WORLDS_DIR = Path(__file__).resolve().parent.parent / 'worlds'


# --------------------------------------------------------------------------------------------
# Shape primitives
# --------------------------------------------------------------------------------------------
@dataclass
class Box:
    name: str
    x: float                 # centre
    y: float
    sx: float                # size
    sy: float
    sz: float
    material: str = 'Gazebo/Grey'
    z: float = None          # centre height; default: resting on the floor
    collide: bool = True     # False = decoration only (robot & lidar pass through it)
    visual_scale: float = 1.0  # shrink the visual (not the collision) to show seams between units
    transparency: float = 0.0


@dataclass
class Cylinder:
    name: str
    x: float
    y: float
    radius: float
    height: float
    material: str = 'Gazebo/Grey'


def wall(name, x1, y1, x2, y2, thickness, height, material):
    """Axis-aligned wall segment from (x1, y1) to (x2, y2)."""
    return Box(name, (x1 + x2) / 2, (y1 + y2) / 2,
               abs(x2 - x1) + thickness, abs(y2 - y1) + thickness, height, material)


def wall_with_doors(name, x1, y1, x2, y2, doors, thickness, height, material):
    """Axis-aligned wall from (x1, y1) to (x2, y2) with gaps.

    doors: list of (centre, width) measured along the wall's own axis (x for a horizontal wall,
    y for a vertical one). Returns the solid segments between the gaps.
    """
    horizontal = y1 == y2
    a0, a1 = sorted((x1, x2) if horizontal else (y1, y2))
    cuts = sorted((c - w / 2, c + w / 2) for c, w in doors)
    segments, start = [], a0
    for d0, d1 in cuts + [(a1, a1)]:
        if d0 - start > 0.05:
            segments.append((start, d0))
        start = max(start, d1)
    return [wall(f'{name}_{i}', s0, y1, s1, y1, thickness, height, material) if horizontal
            else wall(f'{name}_{i}', x1, s0, x1, s1, thickness, height, material)
            for i, (s0, s1) in enumerate(segments)]


# --------------------------------------------------------------------------------------------
# SDF output
# --------------------------------------------------------------------------------------------
def _material(name):
    return ('<material><script><uri>file://media/materials/scripts/gazebo.material</uri>'
            f'<name>{name}</name></script></material>')


def _link(shape):
    if isinstance(shape, Cylinder):
        geom = (f'<cylinder><radius>{shape.radius}</radius>'
                f'<length>{shape.height}</length></cylinder>')
        vgeom, z, collide, transp = geom, shape.height / 2, True, 0.0
    else:
        geom = f'<box><size>{shape.sx:.3f} {shape.sy:.3f} {shape.sz:.3f}</size></box>'
        s = shape.visual_scale
        vgeom = (f'<box><size>{shape.sx * s:.3f} {shape.sy * s:.3f} {shape.sz:.3f}</size></box>'
                 if s != 1.0 else geom)
        z = shape.z if shape.z is not None else shape.sz / 2
        collide, transp = shape.collide, shape.transparency

    collision = (f'\n        <collision name="collision"><geometry>{geom}</geometry></collision>'
                 if collide else '')
    transparency = f'\n          <transparency>{transp}</transparency>' if transp else ''
    return f"""      <link name="{shape.name}">
        <pose>{shape.x:.3f} {shape.y:.3f} {z:.3f} 0 0 0</pose>{collision}
        <visual name="visual">
          <geometry>{vgeom}</geometry>
          {_material(shape.material)}{transparency}
          <cast_shadows>false</cast_shadows>
        </visual>
      </link>"""


def build_sdf(world_name, description, shapes, camera_pose):
    links = '\n'.join(_link(s) for s in shapes)
    return f"""<?xml version="1.0"?>
<!--
{description}
  GENERATED by scripts/generate_worlds.py; edit the layout there, not this file.
-->
<sdf version="1.6">
  <world name="{world_name}">

    <include><uri>model://sun</uri></include>
    <include><uri>model://ground_plane</uri></include>

    <physics type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>

    <scene>
      <shadows>false</shadows>
      <ambient>0.6 0.6 0.6 1</ambient>
    </scene>

    <gui fullscreen="0">
      <camera name="user_camera">
        <pose>{camera_pose}</pose>
      </camera>
    </gui>

    <model name="{world_name}_layout">
      <static>true</static>
{links}
    </model>

  </world>
</sdf>
"""


