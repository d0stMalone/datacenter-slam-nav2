#!/usr/bin/env python3
"""Generate the Nav2 keep-out filter mask from config/keepout_zones.yaml.

The mask is a greyscale image exactly aligned with the navigation map (same size, resolution
and origin): white = no restriction, black = keep-out, grey = "avoid" (cost in between).
Nav2's map_server publishes it on /keepout_filter_mask and the costmaps' KeepoutFilter
writes it on top of the normal costs.

Usage (from the workspace root):
    python3 src/my_robot/scripts/generate_keepout_mask.py \
        [--zones src/my_robot/config/keepout_zones.yaml] [--map src/my_robot/maps/datahall.yaml]
Writes maps/<map name>_keepout.pgm and .yaml next to the map.
"""
import argparse
import os

import numpy as np
from scipy import ndimage
import yaml

PKG = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))


def polygon_mask(poly, xs, ys):
    """Boolean grid: True where the cell centre (xs, ys) is inside the polygon (even-odd rule)."""
    inside = np.zeros(xs.shape, dtype=bool)
    n = len(poly)
    for i in range(n):
        (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % n]
        # Does a ray going +x from the point cross edge (x1,y1)-(x2,y2)?
        crosses = ((y1 > ys) != (y2 > ys)) & \
            (xs < (x2 - x1) * (ys - y1) / ((y2 - y1) or 1e-12) + x1)
        inside ^= crosses
    return inside


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--zones', default=os.path.join(PKG, 'config', 'keepout_zones.yaml'))
    ap.add_argument('--map', default=os.path.join(PKG, 'maps', 'datahall.yaml'))
    args = ap.parse_args()

    zones_cfg = yaml.safe_load(open(args.zones))
    map_cfg = yaml.safe_load(open(args.map))
    map_dir = os.path.dirname(os.path.abspath(args.map))

    # Read the map image header only to get its size (PGM: "P5\n<w> <h>\n<max>\n").
    with open(os.path.join(map_dir, map_cfg['image']), 'rb') as f:
        assert f.readline().strip() == b'P5', 'expected a binary PGM map'
        line = f.readline()
        while line.startswith(b'#'):
            line = f.readline()
        width, height = map(int, line.split())

    res = map_cfg['resolution']
    ox, oy = map_cfg['origin'][:2]
    dx, dy = zones_cfg['world_to_map_offset']

    # Map-frame coordinates of every cell centre. Row 0 of the grid = bottom of the map.
    xs, ys = np.meshgrid(ox + (np.arange(width) + 0.5) * res,
                         oy + (np.arange(height) + 0.5) * res)

    cost = np.zeros((height, width))   # 0..100, per cell
    for z in zones_cfg['zones']:
        poly = [(x + dx, y + dy) for x, y in z['polygon']]
        inside = polygon_mask(poly, xs, ys)
        zone_cost = np.where(inside, float(z['cost']), 0.0)
        buffer = float(z.get('buffer', 0.0))
        if buffer > 0:
            # Distance (m) of each outside cell to the zone, then a linear fade from 70 % of the
            # zone's cost at its edge down to 0 at `buffer` metres away.
            dist = ndimage.distance_transform_edt(~inside) * res
            fade = np.clip(1.0 - dist / buffer, 0.0, 1.0) * 0.7 * z['cost']
            zone_cost = np.maximum(zone_cost, np.where(inside, 0.0, fade))
        cost = np.maximum(cost, zone_cost)      # overlapping zones: the stricter one wins
        print(f"  {z['name']:14s} cost {z['cost']:3d}  {inside.sum() * res * res:6.1f} m²")

    # Encode for map_server "scale" mode with free_thresh 0 / occupied_thresh 1:
    #   occupancy = (1 - pixel/255) * 100, so pixel = 255 * (1 - cost/100).
    img = np.round(255 * (1.0 - cost / 100.0)).astype(np.uint8)
    img = np.flipud(img)                        # image row 0 = TOP of the map

    base = os.path.splitext(os.path.basename(args.map))[0] + '_keepout'
    with open(os.path.join(map_dir, base + '.pgm'), 'wb') as f:
        f.write(b'P5\n# keep-out mask generated by generate_keepout_mask.py\n')
        f.write(f'{width} {height}\n255\n'.encode())
        f.write(img.tobytes())
    with open(os.path.join(map_dir, base + '.yaml'), 'w') as f:
        f.write('# Generated by scripts/generate_keepout_mask.py from config/keepout_zones.yaml'
                ' -- do not edit by hand.\n')
        yaml.safe_dump({
            'image': base + '.pgm',
            'mode': 'scale',             # keep grey levels (avoid zones), not just black/white
            'resolution': res,
            'origin': map_cfg['origin'],
            'negate': 0,
            'occupied_thresh': 1.0,
            'free_thresh': 0.0,
        }, f, sort_keys=False)
    print(f'wrote {os.path.join(map_dir, base)}.pgm/.yaml ({width}x{height})')


if __name__ == '__main__':
    main()
